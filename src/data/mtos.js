
function slugify(value) {
  return value
    // Bỏ tiền tố phân loại khỏi tên file ảnh, giữ nguyên tên hiển thị.
    .replace(/^\s*\[(?:M|NPV)\]?\s*/i, "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/g, "d")
    .replace(/Đ/g, "d")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

